export function getClaimsStats() {
  const total = MOCK_CLAIMS.length;
  const pending = MOCK_CLAIMS.filter((c) => c.status === 'submitted' || c.status === 'under_review').length;
  const completed = MOCK_CLAIMS.filter((c) => c.status === 'resolved').length;
  const fraudAlerts = MOCK_CLAIMS.filter((c) => c.assessment?.fraud.flagged).length;
  const assessedClaims = MOCK_CLAIMS.filter((c) => c.assessment);
  const averageCost = assessedClaims.reduce((sum, c) => sum + (c.assessment?.estimatedCost ?? 0), 0) / assessedClaims.length;
  const averageConfidence = assessedClaims.reduce((sum, c) => sum + (c.assessment?.confidence ?? 0), 0) / assessedClaims.length;

  return { total, pending, completed, fraudAlerts, averageCost: Math.round(averageCost), averageConfidence: Math.round(averageConfidence) };
}
